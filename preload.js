const { contextBridge, ipcRenderer } = require("electron");

const call = (ch) => (...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld("hub", {
  snapshot: call("hub:snapshot"),
  refresh: call("hub:refresh"),
  install: call("hub:install"),
  cancel: call("hub:cancel"),
  uninstall: call("hub:uninstall"),
  launch: call("hub:launch"),
  openFolder: call("hub:openFolder"),
  openUrl: call("hub:openUrl"),
  locate: call("hub:locate"),
  forget: call("hub:forget"),
  pickFolder: call("hub:pickFolder"),
  setSettings: call("hub:setSettings"),
  hubShortcuts: call("hub:hubShortcuts"),
  addCustom: call("hub:addCustom"),
  removeCustom: call("hub:removeCustom"),
  folderSize: call("hub:folderSize"),
  selfCheck: call("hub:selfCheck"),
  selfRestart: call("hub:selfRestart"),
  onChanged: (fn) => ipcRenderer.on("hub:changed", () => fn()),
  onProgress: (fn) => ipcRenderer.on("hub:progress", (_e, p) => fn(p)),
  onSelfProgress: (fn) => ipcRenderer.on("hub:selfProgress", (_e, p) => fn(p)),
});

contextBridge.exposeInMainWorld("macro", {
  snapshot: call("macro:snapshot"),
  start: call("macro:start"),
  save: call("macro:save"),
  remove: call("macro:delete"),
  run: call("macro:run"),
  test: call("macro:test"),
  stop: call("macro:stop"),
  stopAll: call("macro:stopAll"),
  settings: call("macro:settings"),
  pause: call("macro:pause"),
  recStart: call("macro:recStart"),
  recStop: call("macro:recStop"),
  lab: call("macro:lab"),
  capture: call("macro:capture"),
  exportMacros: call("macro:export"),
  importMacros: call("macro:import"),
  onChanged: (fn) => ipcRenderer.on("macro:changed", () => fn()),
  onLoop: (fn) => ipcRenderer.on("macro:loop", (_e, l) => fn(l)),
  onInput: (fn) => ipcRenderer.on("macro:input", (_e, list) => fn(list)),
  onRecorded: (fn) => ipcRenderer.on("macro:recorded", (_e, r) => fn(r)),
  onNotice: (fn) => ipcRenderer.on("macro:notice", (_e, n) => fn(n)),
});
